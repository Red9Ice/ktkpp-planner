from typing import List
from ortools.sat.python import cp_model


def add_subgroup_contiguity_and_start_constraints(
    model: cp_model.CpModel,
    day_slot_vars: List[cp_model.IntVar],  # Список из 6 бинарных переменных дня [x_1, x_2, ..., x_6]
    max_start_slot: int = 3
):
    """
    Накладывает ограничения на один учебный день подгруппы:
    1. Непрерывность (Contiguity): полное отсутствие окон внутри дня подгруппы.
       Допустимые шаблоны: 000000 (выходной), 111000, 011100, 001110, 000111 и т.д.
    2. Старт дня <= max_start_slot (по умолчанию не позже 3-й пары):
       Если у подгруппы есть занятия, они не могут начинаться с 4-й, 5-й или 6-й пары.
    """
    # Переходы детерминированного конечного автомата (DFA):
    # Состояние 0: Утро до начала занятий (читает 0 -> остается в 0, читает 1 -> переход в 1)
    # Состояние 1: Идут занятия подряд без перерывов (читает 1 -> остается в 1, читает 0 -> переход в 2)
    # Состояние 2: Занятия завершены (читает 0 -> остается в 2)
    # Попытка прочесть 1 из Состояния 2 запрещена (нет перехода), что математически исключает «окна».
    transitions = [
        (0, 0, 0),  # Свободное время до первой пары
        (0, 1, 1),  # Начало первой пары
        (1, 1, 1),  # Последующие непрерывные пары
        (1, 0, 2),  # Окончание занятий на день
        (2, 0, 2),  # Свободное время после окончания занятий
    ]

    model.AddAutomaton(
        day_slot_vars,
        starting_state=0,
        final_states=[0, 1, 2],
        transition_expressions=transitions
    )

    # Ограничение start <= max_start_slot:
    # Если пары 1..max_start_slot равны 0 (сумма = 0), то последующие пары (4, 5, 6) также обязаны быть 0.
    morning_sum = sum(day_slot_vars[:max_start_slot])
    for s in range(max_start_slot, len(day_slot_vars)):
        model.Add(day_slot_vars[s] <= morning_sum)
